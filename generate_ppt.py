"""Generate Capstone 1 viva presentation as a .pptx file."""

from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN

# ── Colour palette ────────────────────────────────────────────────────────────
DARK_BLUE  = RGBColor(0x0D, 0x1B, 0x2A)   # slide background
ACCENT     = RGBColor(0x00, 0xB4, 0xD8)   # headings / highlights
WHITE      = RGBColor(0xFF, 0xFF, 0xFF)
LIGHT_GREY = RGBColor(0xCC, 0xD6, 0xE0)
ORANGE     = RGBColor(0xFF, 0x6B, 0x35)

W, H = Inches(13.33), Inches(7.5)         # 16:9 widescreen


def _bg(slide, colour: RGBColor = DARK_BLUE) -> None:
    """Fill slide background with a solid colour."""
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = colour


def _box(slide, left, top, width, height, text, size=20, bold=False,
         colour=WHITE, align=PP_ALIGN.LEFT, italic=False):
    """Add a text box to the slide."""
    txb = slide.shapes.add_textbox(left, top, width, height)
    tf  = txb.text_frame
    tf.word_wrap = True
    p   = tf.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    run.text = text
    run.font.size    = Pt(size)
    run.font.bold    = bold
    run.font.italic  = italic
    run.font.color.rgb = colour
    return txb


def _accent_bar(slide, top=Inches(1.15)):
    """Thin horizontal accent line under slide title."""
    bar = slide.shapes.add_shape(1, Inches(0.4), top, Inches(12.53), Pt(3))
    bar.fill.solid()
    bar.fill.fore_color.rgb = ACCENT
    bar.line.fill.background()


def _title(slide, text):
    _box(slide, Inches(0.4), Inches(0.25), Inches(12.5), Inches(0.85),
         text, size=32, bold=True, colour=ACCENT, align=PP_ALIGN.LEFT)
    _accent_bar(slide)


def _bullet_block(slide, top, items: list[tuple[str, str]], col=WHITE):
    """Render (label, detail) bullet pairs."""
    y = top
    for label, detail in items:
        _box(slide, Inches(0.6), y, Inches(12), Inches(0.35),
             f"▸  {label}", size=16, bold=True, colour=ACCENT)
        y += Inches(0.32)
        if detail:
            _box(slide, Inches(1.1), y, Inches(11.5), Inches(0.32),
                 detail, size=14, colour=LIGHT_GREY)
            y += Inches(0.32)
    return y


