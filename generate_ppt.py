    prs = Presentation()
    prs.slide_width  = W
    prs.slide_height = H

    slide_title(prs)
    slide_problem(prs)
    slide_solution(prs)
    slide_architecture(prs)
    slide_tech_stack(prs)
    slide_rbac(prs)
    slide_key_features(prs)
